"""A repository full of broken files must never crash a scan (NFR-REL-1, NFR-SAFE-8, T-07, T-09).

Text-like cases are committed in tests/fixtures/malformed_repo. Those needing generated bytes, or too
large to be worth committing, are added here at test time.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest
from typer.testing import CliRunner

from _helpers import PERSONA, git, init_repo, rules_found, scan, write_tree
from reviewblind import cli
from reviewblind.config import write_config
from reviewblind.models import SkipReason, Target
from reviewblind.scanners.pdf import load_pymupdf

FIXTURE = Path(__file__).parent / "fixtures" / "malformed_repo"
runner = CliRunner()


def _encrypted_pdf() -> bytes:
    pymupdf = load_pymupdf()
    document = pymupdf.open()
    document.new_page()
    content: bytes = document.tobytes(
        encryption=pymupdf.PDF_ENCRYPT_AES_256, user_pw="u", owner_pw="o"
    )
    document.close()
    return content


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    root = tmp_path / "repo"
    shutil.copytree(FIXTURE, root)
    write_tree(
        root,
        {
            "deep.ipynb": "[" * 200_000,
            "package.json": "[" * 200_000,
            "encrypted.pdf": _encrypted_pdf(),
            "binary_named.py": b"MZ\x00\x01\x02binary",
            "latin1.txt": b"caf\xe9 au lait\n",
            "late_bad_bytes.txt": b"x" * 10_000 + b"\xff\xfe",
            "empty.pdf": b"",
            "empty.png": b"",
            "empty.ipynb": b"",
            "empty.txt": b"",
            "null_bytes.tex": b"\\author{\x00\x00}",
        },
    )
    return root


@pytest.mark.parametrize("target", list(Target))
def test_every_broken_file_is_recorded_and_nothing_crashes(repo: Path, target: Target) -> None:
    report = scan(repo, target)
    assert report.result.incomplete
    assert not [
        item for item in report.result.skipped if item.reason is SkipReason.SCANNER_ERROR
    ], "a scanner failed instead of handling the file"
    reasons = {item.path: item.reason for item in report.result.skipped}
    assert reasons["truncated.ipynb"] is SkipReason.CORRUPT
    assert reasons["deep.ipynb"] is SkipReason.CORRUPT
    assert reasons["pyproject.toml"] is SkipReason.CORRUPT
    assert reasons["CITATION.cff"] is SkipReason.CORRUPT
    assert reasons["setup.py"] is SkipReason.CORRUPT
    assert reasons["package.json"] is SkipReason.CORRUPT
    assert reasons["corrupt.pdf"] is SkipReason.CORRUPT
    assert reasons["empty.pdf"] is SkipReason.CORRUPT
    assert reasons["corrupt.png"] is SkipReason.CORRUPT
    assert reasons["empty.png"] is SkipReason.CORRUPT
    assert reasons["encrypted.pdf"] is SkipReason.ENCRYPTED
    assert reasons["binary_named.py"] is SkipReason.UNSUPPORTED_BINARY
    assert reasons["latin1.txt"] is SkipReason.UNSUPPORTED_BINARY
    assert reasons["late_bad_bytes.txt"] is SkipReason.UNSUPPORTED_BINARY


def test_images_that_cannot_be_read_still_need_a_visual_review(repo: Path) -> None:
    found = [item.artifact for item in scan(repo).result.findings if item.rule_id == "RB703"]
    assert sorted(found) == ["corrupt.png", "empty.png"]


def test_a_readable_file_next_to_broken_ones_is_still_scanned(repo: Path) -> None:
    write_tree(repo, {"leak.txt": "by Alice Example\n"})
    assert "RB101" in rules_found(scan(repo).result.findings)


def test_text_in_a_broken_manifest_is_still_scanned(repo: Path) -> None:
    write_tree(repo, {"pyproject.toml": "[project\n# by Alice Example\n"})
    assert "RB101" in rules_found(scan(repo).result.findings)


def test_the_cli_reports_it_and_uses_the_incomplete_exit_code(repo: Path, tmp_path: Path) -> None:
    config = tmp_path / "private.toml"
    write_config(PERSONA, config)
    relaxed = runner.invoke(cli.app, ["scan", str(repo), "--config", str(config)])
    assert relaxed.exit_code == 0
    assert "Scan complete: NO" in relaxed.stdout
    assert "RESULT: MANUAL REVIEW REQUIRED" in relaxed.stdout
    strict = runner.invoke(cli.app, ["scan", str(repo), "--config", str(config), "--strict"])
    assert strict.exit_code == 3


@pytest.mark.parametrize("output_format", ["json", "markdown"])
def test_every_report_format_survives(repo: Path, tmp_path: Path, output_format: str) -> None:
    config = tmp_path / "private.toml"
    write_config(PERSONA, config)
    result = runner.invoke(
        cli.app, ["scan", str(repo), "--config", str(config), "--format", output_format]
    )
    assert result.exit_code == 0
    assert "corrupt.pdf" in result.stdout


def test_discovery_survives_too(repo: Path) -> None:
    result = runner.invoke(cli.app, ["discover", str(repo)])
    assert result.exit_code == 0
    assert "could not be parsed" in result.stderr


def test_it_also_works_as_a_git_repository(repo: Path) -> None:
    init_repo(repo, {"added.txt": "x\n"})
    git(repo, "status")
    report = scan(repo)
    assert report.result.incomplete
    assert not [item for item in report.result.skipped if item.reason is SkipReason.SCANNER_ERROR]
